import os

from quantumbio_moe.reporting import (Report, curate, curation_prompt, export,
                                     to_markdown, to_text)
from quantumbio_moe.reporting.curator import _extract_title


def _report() -> Report:
    return Report(
        title="CRISPR Off-Target Analysis",
        source="prompt with atgc sequence info",
        draft="# CRISPR Off-Target Analysis\n## Summary\n- Off-target rate low\n## Details\nMore notes.",
        expert="genomic",
        model="quantumbio-moe-local",
        prompt_tokens=10,
        completion_tokens=24,
    )


def test_markdown_export_has_header_and_body():
    text = to_markdown(_report())
    assert "# CRISPR Off-Target Analysis" in text
    assert "**Generated by** QuantumBio-LocalMoE" in text
    assert "**Expert** `genomic`" in text
    assert "## Summary" in text


def test_text_export_is_plain():
    text = to_text(_report())
    assert "##" not in text
    assert text.upper().find("SUMMARY") != -1
    assert "Off-target rate low" in text


def test_export_extensions(tmp_path):
    report = _report()
    md_path = export(report, "md", out_dir=str(tmp_path))
    assert md_path.endswith(".md")
    assert os.path.isfile(md_path)
    txt_path = export(report, "txt", out_dir=str(tmp_path))
    assert txt_path.endswith(".txt")


def test_export_pdf_starts_with_pdf_magic(tmp_path):
    pdf_path = export(_report(), "pdf", out_dir=str(tmp_path))
    with open(pdf_path, "rb") as handle:
        assert handle.read(4) == b"%PDF"


def test_export_pptx_is_zip(tmp_path):
    pptx_path = export(_report(), "pptx", out_dir=str(tmp_path))
    with open(pptx_path, "rb") as handle:
        assert handle.read(2) == b"PK"


def test_title_extraction():
    assert _extract_title("# Hello World\n## Summary", None) == "Hello World"
    assert _extract_title("no heading here", "A Topic") == "A Topic"
    assert _extract_title("no heading here", None) == "QuantumBio-LocalMoE Report"


def test_curation_prompt_includes_source():
    prompt = curation_prompt("the raw output", topic="Toxicity screen")
    assert "the raw output" in prompt
    assert "Toxicity screen" in prompt
    assert "Summary" in prompt


def test_curate_returns_contract():
    class FakeEngine:
        async def generate(self, prompt, expert=None, params=None, system_prompt=None):
            from quantumbio_moe.schemas import GenerationResponse
            return GenerationResponse(
                text="# Molecule Review\n## Summary\n- ok", expert="general",
                model="fake", prompt_tokens=8, completion_tokens=5)

    import asyncio
    result = asyncio.run(curate(FakeEngine(), "source"))
    assert result["title"] == "Molecule Review"
    assert result["draft"].startswith("# Molecule Review")
    assert result["expert"] == "general"