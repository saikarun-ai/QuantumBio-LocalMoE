import os
import re
import time

from .models import Report

ENCODING = "utf-8"


def _plain(text: str) -> str:
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    return text.replace("**", "").replace("`", "").replace("*", "").strip()


def _body(report: Report) -> str:
    return re.sub(r"^\s*#\s+.+\n?", "", report.draft or report.source, count=1).strip()


def to_markdown(report: Report) -> str:
    lines = [
        f"# {report.title}",
        "",
        f"> **Generated by** QuantumBio-LocalMoE  ·  {report.created_iso}",
        f"> **Expert** `{report.expert}`  ·  **Model** `{report.model}`",
        f"> **Tokens** {report.prompt_tokens}+{report.completion_tokens}",
        "",
        "---",
        "",
        _body(report),
        "",
    ]
    return "\n".join(lines)


def to_text(report: Report) -> str:
    out = [
        f"{report.title}",
        "=" * len(report.title),
        "",
        f"Generated by QuantumBio-LocalMoE - {report.created_iso}",
        f"Expert: {report.expert}  Model: {report.model}",
        f"Tokens: {report.prompt_tokens}+{report.completion_tokens}",
        "",
    ]
    for line in _body(report).splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            out.extend(["", stripped[3:].upper()])
        elif stripped.startswith("### "):
            out.extend(["", stripped[4:].upper()])
        elif stripped.startswith("- ") or stripped.startswith("* "):
            out.append("- " + _plain(stripped[2:]))
        elif stripped:
            out.append(_plain(stripped))
    return "\n".join(out) + "\n"


def to_pdf(report: Report, path: str) -> None:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import LETTER
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.platypus import (ListItem, ListFlowable, Paragraph, SimpleDocTemplate, Spacer)

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("ReportTitle", parent=styles["Title"], fontSize=20,
                                 spaceAfter=4, textColor=colors.HexColor("#0f172a"))
    meta_style = ParagraphStyle("Meta", parent=styles["BodyText"], fontSize=9,
                                textColor=colors.HexColor("#64748b"), spaceAfter=10)
    heading_style = ParagraphStyle("Section", parent=styles["Heading2"], fontSize=14,
                                   textColor=colors.HexColor("#0891b2"), spaceBefore=12, spaceAfter=4)
    body_style = ParagraphStyle("Body", parent=styles["BodyText"], fontSize=10.5,
                                leading=15, textColor=colors.HexColor("#1e293b"))

    def bullet_flow(items):
        return ListFlowable(
            [ListItem(Paragraph(item, body_style), leftIndent=16) for item in items],
            bulletType="bullet", leftIndent=12, spaceBefore=1, spaceAfter=1)

    story = [Paragraph(_escape(report.title), title_style),
             Paragraph(f"Generated by QuantumBio-LocalMoE · {report.created_iso} · "
                       f"Expert: {report.expert} · Model: {report.model}", meta_style)]
    bullets: list = []
    for line in _body(report).splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            if bullets:
                story.append(bullet_flow(bullets))
                bullets = []
            story.append(Paragraph(_escape(stripped[3:]), heading_style))
        elif stripped.startswith("### "):
            if bullets:
                story.append(bullet_flow(bullets))
                bullets = []
            story.append(Paragraph(_escape(stripped[4:]),
                                   ParagraphStyle("Sub", parent=heading_style, fontSize=12)))
        elif stripped.startswith("- ") or stripped.startswith("* "):
            bullets.append(stripped[2:].strip())
        elif stripped:
            if bullets:
                story.append(bullet_flow(bullets))
                bullets = []
            story.append(Paragraph(_escape(stripped), body_style))
    if bullets:
        story.append(bullet_flow(bullets))
    story.append(Spacer(1, 16))
    doc = SimpleDocTemplate(path, pagesize=LETTER,
                            leftMargin=54, rightMargin=54, topMargin=54, bottomMargin=54)
    doc.build(story)


def _escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("# ", "")


def to_pptx(report: Report, path: str) -> None:
    from pptx import Presentation
    from pptx.util import Inches, Pt

    prs = Presentation()
    title_layout = prs.slide_layouts[0]
    section_layout = prs.slide_layouts[5]  # Title Only

    slide = prs.slides.add_slide(title_layout)
    slide.shapes.title.text = report.title[:120]
    subtitle = slide.placeholders[1]
    subtitle.text = f"QuantumBio-LocalMoE · {report.created_iso} · " \
                    f"Expert: {report.expert} · Model: {report.model}"

    current = None
    top = Inches(1.6)
    for line in _body(report).splitlines():
        stripped = line.strip()
        if stripped.startswith("## ") or stripped.startswith("### "):
            current = prs.slides.add_slide(section_layout)
            current.shapes.title.text = stripped.lstrip("#").strip()[:80]
            top = Inches(1.6)
        elif (stripped.startswith("- ") or stripped.startswith("* ")) and current is not None:
            box = current.shapes.add_textbox(Inches(0.9), top, Inches(8.2), Inches(0.4))
            box.text_frame.text = "\u2022 " + _plain(stripped[2:])
            box.text_frame.paragraphs[0].font.size = Pt(14)
            top += Inches(0.4)
        elif stripped and current is not None:
            box = current.shapes.add_textbox(Inches(0.9), top, Inches(8.2), Inches(0.6))
            box.text_frame.text = _plain(stripped)
            box.text_frame.paragraphs[0].font.size = Pt(14)
            top += Inches(0.6)

    prs.save(path)


_EXTS = {"markdown": "md", "md": "md", "txt": "txt", "text": "txt",
         "pdf": "pdf", "pptx": "pptx", "pptxgen": "pptx"}


def export(report: Report, fmt: str = "md", out_dir: str = "reports", path: str | None = None) -> str:
    fmt = fmt.lower()
    ext = _EXTS.get(fmt, "md")
    if path is None:
        slug = re.sub(r"[^\w\- ]", "", report.title or "report").strip().replace(" ", "_")
        slug = (re.sub(r"_+", "_", slug)[:40] or "report")
        out_dir = os.path.abspath(out_dir)
        os.makedirs(out_dir, exist_ok=True)
        stamp = time.strftime("%Y%m%d-%H%M%S", time.localtime(report.created_at))
        path = os.path.join(out_dir, f"{slug}_{stamp}.{ext}")

    if ext == "md":
        with open(path, "w", encoding=ENCODING) as handle:
            handle.write(to_markdown(report))
    elif ext == "txt":
        with open(path, "w", encoding=ENCODING) as handle:
            handle.write(to_text(report))
    elif ext == "pdf":
        to_pdf(report, path)
    elif ext == "pptx":
        to_pptx(report, path)
    else:  # pragma: no cover
        raise ValueError(f"unsupported report format: {fmt}")
    return path